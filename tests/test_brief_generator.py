from brief_generator import generate_brief


def sample_data():
    return {
        "repository": "demo-project",
        "total_files": 1,
        "added_lines": 3,
        "removed_lines": 2,
        "changed_files": [
            {"status": "M", "file": "app.py"}
        ],
        "details": {
            "app.py": {
                "affected_symbols_added": ["new_function"],
                "affected_symbols_removed": ["old_function"],
                "added": ["new line"],
                "removed": ["old line"]
            }
        }
    }


def test_generate_brief_includes_header_and_summary():
    brief = generate_brief(sample_data())

    assert "UNVIBECODE DAILY BRIEF" in brief
    assert "Repository: demo-project" in brief
    assert "Files changed: 1" in brief
    assert "Lines added: +3" in brief
    assert "Lines removed: -2" in brief


def test_generate_brief_includes_changed_file():
    brief = generate_brief(sample_data())

    assert "[M] app.py" in brief


def test_generate_brief_includes_added_and_removed_symbols():
    brief = generate_brief(sample_data())

    assert "Symbols affected in current version:" in brief
    assert "- new_function" in brief
    assert "Symbols affected in previous version:" in brief
    assert "- old_function" in brief


def test_generate_brief_includes_added_and_removed_code():
    brief = generate_brief(sample_data())

    assert "Added code:" in brief
    assert "+ new line" in brief
    assert "Removed code:" in brief
    assert "- old line" in brief


def test_generate_brief_handles_no_changed_files():
    data = sample_data()
    data["changed_files"] = []
    data["total_files"] = 0

    brief = generate_brief(data)

    assert "No uncommitted changes found." in brief


def test_generate_brief_handles_missing_file_details():
    data = sample_data()
    data["details"] = {}

    brief = generate_brief(data)

    assert "[M] app.py" in brief
    assert "Added code:" not in brief
    assert "Removed code:" not in brief
    assert "Symbols affected" not in brief


def test_generate_brief_handles_empty_symbols_and_code():
    data = sample_data()
    data["details"]["app.py"] = {
        "affected_symbols_added": [],
        "affected_symbols_removed": [],
        "added": [],
        "removed": []
    }

    brief = generate_brief(data)

    assert "[M] app.py" in brief
    assert "Symbols affected" not in brief
    assert "Added code:" not in brief
    assert "Removed code:" not in brief


def test_generate_brief_limits_added_code_to_five_lines():
    data = sample_data()
    data["details"]["app.py"]["added"] = [
        f"line_{number}" for number in range(1, 8)
    ]

    brief = generate_brief(data)

    assert "+ line_1" in brief
    assert "+ line_5" in brief
    assert "+ line_6" not in brief
    assert "+ line_7" not in brief
    assert "... and 2 more lines" in brief


def test_generate_brief_limits_removed_code_to_five_lines():
    data = sample_data()
    data["details"]["app.py"]["removed"] = [
        f"old_line_{number}" for number in range(1, 8)
    ]

    brief = generate_brief(data)

    assert "- old_line_1" in brief
    assert "- old_line_5" in brief
    assert "- old_line_6" not in brief
    assert "- old_line_7" not in brief
    assert "... and 2 more lines" in brief


def test_generate_brief_handles_exactly_five_code_lines():
    data = sample_data()
    data["details"]["app.py"]["added"] = [
        f"line_{number}" for number in range(1, 6)
    ]

    brief = generate_brief(data)

    assert "+ line_5" in brief
    assert "... and" not in brief


def test_generate_brief_includes_footer():
    brief = generate_brief(sample_data())

    assert "Generated by UnvibeCode Daily Brief" in brief
    assert brief.endswith("======================================")
