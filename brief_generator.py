def generate_brief(data):
    lines = [
        "======================================",
        "       UNVIBECODE DAILY BRIEF",
        "======================================",
        f"Repository: {data['repository']}",
        "",
        "CHANGE SUMMARY",
        f"Files changed: {data['total_files']}",
        f"Lines added: +{data['added_lines']}",
        f"Lines removed: -{data['removed_lines']}",
        "",
        "CHANGED FILES"
    ]

    for item in data["changed_files"]:
        filename = item["file"]
        detail = data["details"].get(filename, {})

        lines.append(f"\n[{item['status']}] {filename}")

        added_symbols = detail.get("affected_symbols_added", [])
        removed_symbols = detail.get("affected_symbols_removed", [])

        if added_symbols:
            lines.append("  Symbols affected in current version:")
            for symbol in added_symbols:
                lines.append(f"    - {symbol}")

        if removed_symbols:
            lines.append("  Symbols affected in previous version:")
            for symbol in removed_symbols:
                lines.append(f"    - {symbol}")

        for label, key in [
            ("Added code", "added"),
            ("Removed code", "removed")
        ]:
            code_lines = detail.get(key, [])

            if code_lines:
                lines.append(f"  {label}:")

                for code in code_lines[:5]:
                    lines.append(f"    {'+' if key == 'added' else '-'} {code}")

                if len(code_lines) > 5:
                    lines.append(
                        f"    ... and {len(code_lines) - 5} more lines"
                    )

    if not data["changed_files"]:
        lines.append("No uncommitted changes found.")

    lines.extend([
        "",
        "Generated by UnvibeCode Daily Brief",
        "======================================"
    ])

    return "\n".join(lines)
